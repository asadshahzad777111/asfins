export type TranslationKey = keyof typeof translations.en;

export function translate(
  lang: Lang,
  key: TranslationKey,
  params?: Record<string, string | number>
): string {
  let text: string = translations[lang][key] ?? translations.en[key];
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}

const ROOM_KEYS: Record<string, TranslationKey> = {
  kitchen: "roomKitchen",
  bathroom: "roomBathroom",
  basement: "roomBasement",
  "tv-lounge": "roomTvLounge",
  bedroom: "roomBedroom",
  other: "roomOther",
};

export function roomLabel(lang: Lang, categoryId: string): string {
  const key = ROOM_KEYS[categoryId];
  return key ? translate(lang, key) : categoryId;
}
